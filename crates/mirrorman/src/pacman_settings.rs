use mirrorman_core::tr;
use adw::prelude::*;
use std::sync::Arc;
use std::sync::Mutex;

const APT_CONF: &str = "/etc/apt/apt.conf.d/99mirrorman.conf";
const PACMAN_CONF: &str = "/etc/pacman.conf";

struct SettingsConfig {
    ignore_pkg: Vec<String>,
    hold_pkg: Vec<String>,
    no_upgrade: Vec<String>,
    no_extract: Vec<String>,
    sync_first: Vec<String>,
    check_space: bool,
    ilovecandy: bool,
    parallel_downloads: i32,
    clean_method: String,
    architecture: String,
    install_recommends: bool,
    retries: i32,
}

impl SettingsConfig {
    fn load() -> Self {
        if std::path::Path::new("/etc/apt").exists() {
            Self::load_apt()
        } else {
            Self::load_pacman()
        }
    }

    fn load_apt() -> Self {
        let mut cfg = Self::default();
        let content = std::fs::read_to_string(APT_CONF).unwrap_or_default();
        for line in content.lines() {
            let line = line.trim().trim_end_matches(';');
            if let Some((k, v)) = line.split_once(' ') {
                let key = k.trim();
                let val = v.trim().trim_matches('"');
                match key {
                    "Acquire::http::Pipeline-Depth" => {
                        if let Ok(n) = val.parse() {
                            cfg.parallel_downloads = n;
                        }
                    }
                    "Acquire::Retries" => {
                        if let Ok(n) = val.parse() {
                            cfg.retries = n;
                        }
                    }
                    "APT::Install-Recommends" => {
                        cfg.install_recommends = val == "true" || val == "1";
                    }
                    "APT::Color" => {
                        cfg.ilovecandy = val == "1" || val == "true";
                    }
                    "APT::Architecture" => {
                        cfg.architecture = val.to_string();
                    }
                    _ => {}
                }
            }
        }
        cfg
    }

    fn load_pacman() -> Self {
        let content = match std::fs::read_to_string(PACMAN_CONF) {
            Ok(c) => c,
            Err(_) => return Self::default(),
        };

        parse_config(&content)
    }

    fn default() -> Self {
        Self {
            ignore_pkg: Vec::new(),
            hold_pkg: Vec::new(),
            no_upgrade: Vec::new(),
            no_extract: Vec::new(),
            sync_first: Vec::new(),
            check_space: false,
            ilovecandy: true,
            parallel_downloads: 5,
            clean_method: "KeepInstalled".to_string(),
            architecture: "auto".to_string(),
            install_recommends: true,
            retries: 3,
        }
    }

    fn to_apt_conf(&self) -> String {
        let mut s = String::new();
        s.push_str("// Persis OS / Debian APT configuration\n");
        s.push_str("// Generated by mirrorman\n\n");
        s.push_str(&format!("Acquire::http::Pipeline-Depth \"{}\";\n", self.parallel_downloads));
        s.push_str(&format!("Acquire::Retries \"{}\";\n", self.retries));
        s.push_str(&format!("APT::Install-Recommends \"{}\";\n", if self.install_recommends { "true" } else { "false" }));
        s.push_str(&format!("APT::Color \"{}\";\n", if self.ilovecandy { "1" } else { "0" }));
        if self.architecture != "auto" {
            s.push_str(&format!("APT::Architecture \"{}\";\n", self.architecture));
        }
        s
    }
}

pub fn show_settings_sheet(bottom_sheet: &adw::BottomSheet) {
    let config = Arc::new(Mutex::new(SettingsConfig::load()));

    let toolbar_view = adw::ToolbarView::new();

    let header = adw::HeaderBar::new();
    let is_debian = std::path::Path::new("/etc/apt").exists();
    let title_text = if is_debian { tr!("APT Options") } else { tr!("Package Manager Options") };
    let title_label = gtk4::Label::new(Some(title_text));
    title_label.add_css_class("title");
    header.set_title_widget(Some(&title_label));
    toolbar_view.add_top_bar(&header);

    let save_btn = gtk4::Button::with_label(tr!("Save"));
    save_btn.add_css_class("suggested-action");
    header.pack_end(&save_btn);

    let cancel_btn = gtk4::Button::with_label(tr!("Cancel"));
    {
        let bottom_sheet = bottom_sheet.clone();
        cancel_btn.connect_clicked(move |_| {
            bottom_sheet.set_open(false);
        });
    }
    header.pack_start(&cancel_btn);

    let scroll = gtk4::ScrolledWindow::new();
    scroll.set_policy(gtk4::PolicyType::Never, gtk4::PolicyType::Automatic);
    scroll.set_vexpand(true);
    scroll.set_propagate_natural_height(true);
    toolbar_view.set_content(Some(&scroll));

    let box_ = gtk4::Box::new(gtk4::Orientation::Vertical, 12);
    box_.set_margin_top(12);
    box_.set_margin_bottom(12);
    box_.set_margin_start(12);
    box_.set_margin_end(12);
    scroll.set_child(Some(&box_));

    let group = adw::PreferencesGroup::new();
    group.set_title(tr!("Package Management"));
    box_.append(&group);

    let cfg = config.lock().unwrap_or_else(|e| e.into_inner());

    let parallel_row = adw::ActionRow::new();
    parallel_row.set_title(tr!("Download Pipeline Depth"));
    parallel_row.set_subtitle(tr!("Number of parallel download connections (1-20)"));
    let parallel_spin = gtk4::SpinButton::with_range(1.0, 20.0, 1.0);
    parallel_spin.set_value(cfg.parallel_downloads as f64);
    parallel_row.add_suffix(&parallel_spin);
    group.add(&parallel_row);

    let color_row = adw::ActionRow::new();
    color_row.set_title(tr!("Colored Terminal Output"));
    color_row.set_subtitle(tr!("Enable colored output in package manager terminal"));
    let color_switch = gtk4::Switch::new();
    color_switch.set_valign(gtk4::Align::Center);
    color_switch.set_active(cfg.ilovecandy);
    color_row.add_suffix(&color_switch);
    color_row.set_activatable_widget(Some(&color_switch));
    group.add(&color_row);

    let recommends_row = adw::ActionRow::new();
    recommends_row.set_title(tr!("Install Recommends"));
    recommends_row.set_subtitle(tr!("Automatically install recommended packages"));
    let recommends_switch = gtk4::Switch::new();
    recommends_switch.set_valign(gtk4::Align::Center);
    recommends_switch.set_active(cfg.install_recommends);
    recommends_row.add_suffix(&recommends_switch);
    recommends_row.set_activatable_widget(Some(&recommends_switch));
    group.add(&recommends_row);

    let arch_row = adw::ComboRow::new();
    arch_row.set_title(tr!("Architecture"));
    arch_row.set_subtitle(tr!("System package architecture"));
    let arch_store = gtk4::StringList::new(&[tr!("auto"), "amd64", "arm64", "i386"]);
    arch_row.set_model(Some(&arch_store));
    arch_row.set_selected(match cfg.architecture.as_str() {
        "amd64" => 1,
        "arm64" => 2,
        "i386" => 3,
        _ => 0,
    });
    group.add(&arch_row);

    let auto_group = adw::PreferencesGroup::new();
    auto_group.set_title(tr!("Auto Refresh Timer"));
    auto_group.set_description(Some(tr!("Automatically update mirror sources on a systemd timer schedule")));
    box_.append(&auto_group);

    let auto_row = adw::ActionRow::new();
    auto_row.set_title(tr!("Enable Auto Refresh"));
    auto_row.set_subtitle(tr!("Run systemd background timer unit (mirrorman-refresh.timer)"));
    let auto_switch = gtk4::Switch::new();
    auto_switch.set_valign(gtk4::Align::Center);
    let timer_active = std::process::Command::new("systemctl")
        .args(["--user", "is-active", "mirrorman-refresh.timer"])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim() == "active")
        .unwrap_or(false);
    auto_switch.set_active(timer_active);
    auto_row.add_suffix(&auto_switch);
    auto_row.set_activatable_widget(Some(&auto_switch));
    auto_group.add(&auto_row);

    drop(cfg);

    let cfg_clone = config.clone();
    let bottom_sheet_save = bottom_sheet.clone();
    save_btn.connect_clicked(move |_| {
        if auto_switch.is_active() {
            let _ = std::process::Command::new("systemctl")
                .args(["--user", "enable", "--now", "mirrorman-refresh.timer"])
                .status();
        } else {
            let _ = std::process::Command::new("systemctl")
                .args(["--user", "disable", "--now", "mirrorman-refresh.timer"])
                .status();
        }

        let mut cfg = cfg_clone.lock().unwrap_or_else(|e| e.into_inner());
        cfg.parallel_downloads = parallel_spin.value() as i32;
        cfg.ilovecandy = color_switch.is_active();
        cfg.install_recommends = recommends_switch.is_active();
        cfg.architecture = match arch_row.selected() {
            1 => "amd64".to_string(),
            2 => "arm64".to_string(),
            3 => "i386".to_string(),
            _ => "auto".to_string(),
        };

        if is_debian {
            let apt_conf_str = cfg.to_apt_conf();
            let _ = mirrorman_core::helper_client::HelperClient::save_apt_conf(&apt_conf_str);
        } else {
            let _ = save_pacman_config(&cfg);
        }

        bottom_sheet_save.set_open(false);
    });

    bottom_sheet.set_sheet(Some(&toolbar_view));
    bottom_sheet.set_open(true);
}

fn save_pacman_config(cfg: &SettingsConfig) -> Result<(), String> {
    let content = std::fs::read_to_string(PACMAN_CONF).unwrap_or_default();
    let mut lines = Vec::new();
    let mut in_options = false;

    for line in content.lines() {
        let stripped = line.trim();
        if stripped.eq_ignore_ascii_case("[options]") {
            in_options = true;
            lines.push(line.to_string());
            lines.push(format!("ParallelDownloads = {}", cfg.parallel_downloads));
            if cfg.ilovecandy {
                lines.push("ILoveCandy".to_string());
                lines.push("Color".to_string());
            }
            continue;
        }

        if in_options && stripped.starts_with('[') {
            in_options = false;
        }

        if in_options {
            let key = line_key(stripped);
            if matches!(key, "ParallelDownloads" | "ILoveCandy" | "Color") {
                continue;
            }
        }

        lines.push(line.to_string());
    }

    let result = lines.join("\n");
    mirrorman_core::helper_client::HelperClient::save_pacman_conf(&result)
}

fn parse_config(content: &str) -> SettingsConfig {
    let mut cfg = SettingsConfig::default();
    let mut in_options = false;

    for line in content.lines() {
        let stripped = line.trim();
        if stripped.eq_ignore_ascii_case("[options]") {
            in_options = true;
            continue;
        }
        if in_options && stripped.starts_with('[') && !stripped.eq_ignore_ascii_case("[options]") {
            in_options = false;
            continue;
        }
        if !in_options || stripped.starts_with('#') || stripped.is_empty() {
            continue;
        }

        if let Some((key, val)) = stripped.split_once('=') {
            let key = key.trim();
            let val = val.trim();
            match key {
                "IgnorePkg" => cfg.ignore_pkg = val.split_whitespace().map(|s| s.to_string()).collect(),
                "HoldPkg" => cfg.hold_pkg = val.split_whitespace().map(|s| s.to_string()).collect(),
                "NoUpgrade" => cfg.no_upgrade = val.split_whitespace().map(|s| s.to_string()).collect(),
                "NoExtract" => cfg.no_extract = val.split_whitespace().map(|s| s.to_string()).collect(),
                "SyncFirst" => cfg.sync_first = val.split_whitespace().map(|s| s.to_string()).collect(),
                "ParallelDownloads" => {
                    if let Ok(n) = val.parse() {
                        cfg.parallel_downloads = n;
                    }
                }
                "CleanMethod" => cfg.clean_method = val.to_string(),
                "Architecture" => cfg.architecture = val.to_string(),
                _ => {}
            }
        } else {
            let key = stripped.trim();
            match key {
                "CheckSpace" => cfg.check_space = true,
                "ILoveCandy" => cfg.ilovecandy = true,
                _ => {}
            }
        }
    }
    cfg
}

fn line_key(line: &str) -> &str {
    let trimmed = line.trim();
    if trimmed.starts_with('#') || trimmed.is_empty() {
        return "";
    }
    if let Some((k, _)) = trimmed.split_once('=') {
        k.trim()
    } else {
        trimmed
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_default_config() {
        let content = "[options]\n#ParallelDownloads = 5\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.parallel_downloads, 5);
        assert!(cfg.ilovecandy);
    }

    #[test]
    fn parse_ignore_pkg() {
        let content = "[options]\nIgnorePkg = linux linux-headers\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.ignore_pkg, vec!["linux", "linux-headers"]);
    }

    #[test]
    fn parse_hold_pkg() {
        let content = "[options]\nHoldPkg = glibc pacman\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.hold_pkg, vec!["glibc", "pacman"]);
    }

    #[test]
    fn parse_parallel_downloads() {
        let content = "[options]\nParallelDownloads = 10\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.parallel_downloads, 10);
    }

    #[test]
    fn parse_boolean_flags() {
        let content = "[options]\nCheckSpace\nILoveCandy\n";
        let cfg = parse_config(content);
        assert!(cfg.check_space);
        assert!(cfg.ilovecandy);
    }

    #[test]
    fn parse_architecture() {
        let content = "[options]\nArchitecture = x86_64_v3\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.architecture, "x86_64_v3");
    }

    #[test]
    fn parse_clean_method() {
        let content = "[options]\nCleanMethod = KeepCurrent\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.clean_method, "KeepCurrent");
    }

    #[test]
    fn parse_commented_lines_ignored() {
        let content = "[options]\n#IgnorePkg = firefox\n#CheckSpace\n";
        let cfg = parse_config(content);
        assert!(cfg.ignore_pkg.is_empty());
        assert!(!cfg.check_space);
    }

    #[test]
    fn parse_stops_at_next_section() {
        let content = "[options]\nIgnorePkg = firefox\nParallelDownloads = 10\n\n[core]\nInclude = /etc/pacman.d/mirrorlist\nIgnorePkg = should-not-parse\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.ignore_pkg, vec!["firefox"]);
        assert_eq!(cfg.parallel_downloads, 10);
    }

    #[test]
    fn parse_no_upgrade_no_extract() {
        let content = "[options]\nNoUpgrade = etc/pacman.d/mirrorlist\nNoExtract = usr/share/doc/*\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.no_upgrade, vec!["etc/pacman.d/mirrorlist"]);
        assert_eq!(cfg.no_extract, vec!["usr/share/doc/*"]);
    }

    #[test]
    fn parse_sync_first() {
        let content = "[options]\nSyncFirst = pacman\n";
        let cfg = parse_config(content);
        assert_eq!(cfg.sync_first, vec!["pacman"]);
    }

    #[test]
    fn line_key_returns_empty_for_comments() {
        assert_eq!(line_key("#IgnorePkg = foo"), "");
    }

    #[test]
    fn line_key_extracts_key() {
        assert_eq!(line_key("IgnorePkg = foo"), "IgnorePkg");
        assert_eq!(line_key("CheckSpace"), "CheckSpace");
    }
}
