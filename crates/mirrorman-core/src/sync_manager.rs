pub struct SyncManager;

impl SyncManager {
    pub fn sync_repositories() -> Result<String, String> {
        Self::run_apt(&["update"], "sync repositories")
    }

    pub fn clean_cache() -> Result<String, String> {
        Self::run_apt(&["clean"], "clean package cache")
    }

    pub fn backup_mirrorlist() -> Result<String, String> {
        let timestamp = chrono::Local::now().format("%Y%m%d_%H%M%S");
        let target_source = if std::path::Path::new(crate::mirror_manager::SOURCES_DEB822_FILE).exists() {
            crate::mirror_manager::SOURCES_DEB822_FILE
        } else if std::path::Path::new(crate::mirror_manager::SOURCES_LIST_FILE).exists() {
            crate::mirror_manager::SOURCES_LIST_FILE
        } else {
            "/etc/pacman.d/mirrorlist"
        };

        let backup_path = format!("{target_source}.backup.{timestamp}");
        let (success, _, stderr) = crate::helper_client::HelperClient::run_command(
            "cp",
            &[target_source, &backup_path],
        )?;
        if success {
            Self::rotate_backups(10, target_source)?;
            Ok(backup_path)
        } else {
            Err(format!("Failed to backup sources list: {stderr}"))
        }
    }

    fn rotate_backups(max_backups: usize, target_source: &str) -> Result<(), String> {
        let base_path = std::path::Path::new(target_source);
        let parent = base_path.parent().unwrap_or(std::path::Path::new("/etc/apt"));
        let prefix = format!("{}.backup.", base_path.file_name().unwrap_or_default().to_string_lossy());

        let mut backups: Vec<std::path::PathBuf> = std::fs::read_dir(parent)
            .map_err(|e| format!("Failed to read backup dir: {e}"))?
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| {
                p.file_name()
                    .is_some_and(|f| f.to_string_lossy().starts_with(&prefix))
            })
            .collect();

        backups.sort();
        while backups.len() >= max_backups {
            if let Some(oldest) = backups.first() {
                let _ = std::fs::remove_file(oldest);
                backups.remove(0);
            } else {
                break;
            }
        }
        Ok(())
    }

    pub fn generate_share_content(mirrors: &[crate::mirror_manager::Mirror]) -> String {
        let mut s = String::new();
        s.push_str("## Persis OS / Debian Mirror Configuration\n");
        s.push_str(&format!(
            "## Generated by mirrorman on {}\n##\n\n",
            chrono::Local::now().format("%Y-%m-%d %H:%M:%S")
        ));
        let enabled_count = mirrors.iter().filter(|m| m.enabled).count();
        s.push_str(&format!("## {enabled_count} enabled mirror(s)\n\n"));

        let enabled_mirrors: Vec<_> = mirrors.iter().filter(|m| m.enabled).collect();
        let default_url = "https://deb.debian.org/debian";
        let primary_url = enabled_mirrors
            .first()
            .map(|m| m.url.trim_end_matches('/'))
            .unwrap_or(default_url);

        s.push_str(&format!("deb {primary_url} trixie main contrib non-free non-free-firmware\n"));
        s.push_str(&format!("deb-src {primary_url} trixie main contrib non-free non-free-firmware\n\n"));
        s.push_str(&format!("deb {primary_url} trixie-updates main contrib non-free non-free-firmware\n"));
        s.push_str(&format!("deb-src {primary_url} trixie-updates main contrib non-free non-free-firmware\n\n"));
        s.push_str("deb http://security.debian.org/debian-security trixie-security main contrib non-free non-free-firmware\n");
        s.push_str("deb-src http://security.debian.org/debian-security trixie-security main contrib non-free non-free-firmware\n");

        s
    }

    fn run_apt(args: &[&str], label: &str) -> Result<String, String> {
        let (success, stdout, stderr) = crate::helper_client::HelperClient::run_apt(args)?;
        if success {
            Ok(stdout)
        } else {
            Err(format!("Failed to {label}:\n{stderr}"))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::mirror_manager::Mirror;

    #[test]
    fn test_generate_share_content() {
        let mirrors = vec![
            Mirror {
                url: "https://mirror.iranserver.com/debian".to_string(),
                country: "Iran".to_string(),
                country_code: "IR".to_string(),
                protocol: "https".to_string(),
                speed: Some(10.0),
                last_sync: None,
                enabled: true,
                ipv4: true,
                ipv6: false,
                completion_pct: None,
                score: None,
                duration_avg: None,
                duration_stddev: None,
            },
            Mirror {
                url: "https://mirror.de/debian".to_string(),
                country: "Germany".to_string(),
                country_code: "DE".to_string(),
                protocol: "https".to_string(),
                speed: Some(50.0),
                last_sync: None,
                enabled: false,
                ipv4: true,
                ipv6: false,
                completion_pct: None,
                score: None,
                duration_avg: None,
                duration_stddev: None,
            },
        ];

        let shared = SyncManager::generate_share_content(&mirrors);
        assert!(shared.contains("## Persis OS / Debian Mirror Configuration"));
        assert!(shared.contains("## 1 enabled mirror(s)"));
        assert!(shared.contains("deb https://mirror.iranserver.com/debian trixie main"));
        assert!(!shared.contains("mirror.de"));
    }
}
